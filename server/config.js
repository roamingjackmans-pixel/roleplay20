// Server configuration. Values come from environment variables, optionally loaded from `.env` in the repo root.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const envFile = path.join(ROOT, '.env');
if (fs.existsSync(envFile)) {
  try { process.loadEnvFile(envFile); } catch (e) { console.warn('[config] could not read .env:', e.message); }
}

const env = process.env;
const num = (v, d) => (v === undefined || v === '' ? d : Number(v));
// command-line overrides: --no-tunnel, --ai=file|api|off, --port=3021
for (const arg of process.argv.slice(2)) {
  if (arg === '--no-tunnel') env.TUNNEL = 'off';
  const m = /^--(ai|port|data)=(.+)$/.exec(arg);
  if (m) env[{ ai: 'AI_PROVIDER', port: 'PORT', data: 'DATA_DIR' }[m[1]]] = m[2];
}

export const config = {
  port: num(env.PORT, 3020),
  basePath: '/roleplay20',
  dataDir: path.resolve(ROOT, env.DATA_DIR || 'data'),
  clientDist: path.join(ROOT, 'client', 'dist'),
  siteDir: path.join(ROOT, 'site'),
  srdDir: path.join(ROOT, 'shared', 'srd'),

  // Privacy gate. GATE_PASSWORD_HASH is "scrypt$<salt>$<hash>" (see scripts/setup.mjs).
  gateHash: env.GATE_PASSWORD_HASH || '',
  gateMaxFailures: num(env.GATE_MAX_FAILURES, 3),
  gateLockMs: num(env.GATE_LOCK_HOURS, 24) * 3600 * 1000,
  gateTokenDays: num(env.GATE_TOKEN_DAYS, 30),

  // Secret used to sign gate tokens. Generated by setup and stored in .env.
  secret: env.SERVER_SECRET || '',

  // Browsers allowed to call the API from another origin (the GitHub Pages shell).
  allowedOrigins: (env.ALLOWED_ORIGINS || 'https://josephjackman.com,https://www.josephjackman.com,https://roamingjackmans-pixel.github.io')
    .split(',').map((s) => s.trim()).filter(Boolean),

  // AI Dungeon Master. Provider: "api" (Anthropic API key), "file" (developer testing: a human/agent writes the replies),
  // or "off" (no AI: the campaign owner narrates by hand from the DM screen).
  aiProvider: env.AI_PROVIDER || (env.ANTHROPIC_API_KEY ? 'api' : 'off'),
  anthropicKey: env.ANTHROPIC_API_KEY || '',
  defaultModel: env.DM_MODEL || 'claude-opus-5-5',
  defaultEffort: env.DM_EFFORT || 'medium',
  aiTimeoutMs: num(env.AI_TIMEOUT_SECONDS, 240) * 1000,

  // Public URL discovery for the GitHub Pages shell.
  tunnel: env.TUNNEL || 'auto',                // auto | cloudflared | off
  publicUrl: env.PUBLIC_URL || '',             // set when you run your own named tunnel / reverse proxy
  publishRepo: env.PUBLISH_REPO || 'roamingjackmans-pixel/roleplay20',
  publishBranch: env.PUBLISH_BRANCH || 'live',
  cloudflaredPath: env.CLOUDFLARED_PATH || '',
};

fs.mkdirSync(config.dataDir, { recursive: true });
