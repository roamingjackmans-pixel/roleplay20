/**
 * Player's Handbook (2014) spells that the SRD leaves out. Same shape as shared/srd/spells.json (see the header of
 * scripts/build-srd.mjs), plus `srd: false`. Descriptions are written for Roleplay20 in our own words; the numbers
 * (dice, saves, ranges, areas, durations) follow the standard 5e rules so the app's automation works.
 *
 * Notes on how the data is filled:
 * - Spells that trigger on your next weapon hit (smites, ensnaring strike, hail of thorns, lightning arrow) are stored
 *   like the SRD's branding-smite: `damage` holds the extra dice, `dc` is null, so the app doesn't roll a save or deal
 *   the damage at cast time. The save that rides on the hit is in the description for the DM.
 * - Lingering effects (hex, cloud of daggers, hunger of Hadar...) keep their per-hit or per-turn dice in `damage`.
 * - Healing without the caster's modifier must not say "spellcasting ability modifier" in `desc` (combat.js adds the
 *   modifier when it finds that phrase).
 */

/** { "<from>": f(from), ..., "9": f(9) } */
const slots = (from, f) => Object.fromEntries(Array.from({ length: 10 - from }, (_, i) => [String(from + i), f(from + i)]));
/** Dice that grow by `step` dice per slot level above the spell's level: grow(1, 2, "d6") -> 1: 2d6, 2: 3d6 ... */
const grow = (from, base, die, step = 1) => slots(from, (l) => `${base + step * (l - from)}${die}`);
/** The same dice at every slot level. */
const flat = (from, dice) => slots(from, () => dice);
/** Cantrip dice at character levels 1, 5, 11 and 17. */
const cantrip = (die) => ({ 1: `1${die}`, 5: `2${die}`, 11: `3${die}`, 17: `4${die}` });

